#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T6-B/C: run the screening/linearization probe corpus through the oracle.

Inputs (generated by tools/oracle/make_screen_probes.py):
  cmyk_ramp16_160.tif / cmyk_patch20_100.tif / cmyk_white_100.tif /
  cmyk_full_100.tif / cmyk_full4_100.tif / cmyk_probe_<ink><val>_64.tif
  rgb_gray16_160.png / rgb_ramps16_160.png
Machines/modes: a3dtf1390 mode2 + mode0, h13xp600 mode0.
Each run: PRN -> reference/prn_samples/probe_screen_*.prn, job JSON + response
-> reference/jobs/.  Single-patch probes add "mtcount": true so the official
dot-size statistics are returned in the response.

Result summary: work/protocol/evidence/screen_probe_raw.json
All POSTs sequential.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(WS, "tools", "oracle"))
import mtrip_oracle as O   # noqa: E402

EV = os.path.join(HERE, "evidence")
PRS = {"a3dtf1390": "./A3-DTF-1390.prs", "h13xp600": O.PRS["h13xp600"]}
INK_LEVELS = [(ink, v) for ink in ("C", "M", "Y", "K")
              for v in (0, 64, 128, 192, 255)]


def run(case, image_file, machine, mode, extra=None, tag_suffix=""):
    stem = "probe_screen_%s_%s_m%d%s" % (case, machine, mode, tag_suffix)
    img = os.path.join(O.INPUTS, image_file).replace("\\", "/")
    out = os.path.join(O.PRNS, stem + ".prn").replace("\\", "/")
    job = O.build_job(img, PRS[machine], mode, out, extra=extra)
    r = O.run_job(job, stem)
    rec = {"stem": stem, "case": case, "image": image_file, "machine": machine,
           "mode": mode, "extra": extra, "result": r["response"].get("result"),
           "error": r["response"].get("error"),
           "elapsed_s": r["response"].get("_elapsed_s"),
           "prn": out, "size": r["prn_size"]}
    if "mtcount" in r["response"]:
        rec["mtcount"] = r["response"]["mtcount"]
    print("%-52s result=%s size=%-9s%s" % (
        stem, rec["result"], rec["size"],
        (" mtcount=%s" % json.dumps(rec["mtcount"], ensure_ascii=False)[:120])
        if "mtcount" in rec else ""))
    return rec


def main():
    os.makedirs(EV, exist_ok=True)
    rows = []
    # --- B1. main CMYK probe images on 3 machine/mode combos ---
    for case, fn in [
        ("cmyk_ramp16_160", "cmyk_ramp16_160.tif"),
        ("cmyk_patch20_100", "cmyk_patch20_100.tif"),
        ("cmyk_white_100", "cmyk_white_100.tif"),
        ("cmyk_full_100", "cmyk_full_100.tif"),
        ("cmyk_full4_100", "cmyk_full4_100.tif"),
    ]:
        for machine, mode in (("a3dtf1390", 2), ("a3dtf1390", 0), ("h13xp600", 0)):
            rows.append(run(case, fn, machine, mode))
    # --- B2. single solid patches with official mtcount statistics (A3 m2/m0) ---
    for ink, v in INK_LEVELS:
        fn = "cmyk_probe_%s%d_64.tif" % (ink, v)
        case = "probe_%s%d" % (ink, v)
        for mode in (2, 0):
            rows.append(run(case, fn, "a3dtf1390", mode,
                            extra={"mtcount": True}))
    # --- C. RGB probes (chain reverse-engineering for T3) ---
    for case, fn in [("rgb_gray16_160", "rgb_gray16_160.png"),
                     ("rgb_ramps16_160", "rgb_ramps16_160.png")]:
        for machine, mode in (("a3dtf1390", 2), ("a3dtf1390", 0),
                              ("h13xp600", 0)):
            rows.append(run(case, fn, machine, mode))
    with open(os.path.join(EV, "screen_probe_raw.json"), "w",
              encoding="utf-8", newline="\n") as f:
        json.dump(rows, f, ensure_ascii=False, indent=2)
    bad = [r for r in rows if r["result"] != 0]
    print("\nsaved evidence/screen_probe_raw.json (%d runs, %d failed)"
          % (len(rows), len(bad)))
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
